    CONSTRAINT ck_transfer_line_locations_differ CHECK (source_location_id <> destination_location_id),
    CONSTRAINT ck_transfer_line_quantity CHECK (quantity > 0)
);

CREATE TABLE inventory.stocktake (
    stocktake_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_code varchar(60) NOT NULL,
    warehouse_id bigint NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'draft',
    started_at timestamptz NULL,
    submitted_at timestamptz NULL,
    posted_at timestamptz NULL,
    posted_by_user_id bigint NULL,
    notes text NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by_user_id bigint NULL,
    CONSTRAINT uq_stocktake_code UNIQUE (stocktake_code),
    CONSTRAINT fk_stocktake_warehouse FOREIGN KEY (warehouse_id) REFERENCES inventory.warehouse (warehouse_id),
    CONSTRAINT ck_stocktake_status CHECK (status IN ('draft', 'counting', 'submitted', 'approved', 'posted', 'cancelled'))
);

CREATE TABLE inventory.stocktake_line (
    stocktake_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stocktake_id bigint NOT NULL,
    line_number integer NOT NULL,
    stock_item_id bigint NOT NULL,
    warehouse_location_id bigint NOT NULL,
    stock_lot_id bigint NULL,
    system_quantity numeric(18, 6) NOT NULL,
    counted_quantity numeric(18, 6) NULL,
    counted_at timestamptz NULL,
    counted_by_user_id bigint NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_stocktake_line_number UNIQUE (stocktake_id, line_number),
    CONSTRAINT fk_stocktake_line_session FOREIGN KEY (stocktake_id) REFERENCES inventory.stocktake (stocktake_id),
    CONSTRAINT fk_stocktake_line_item FOREIGN KEY (stock_item_id) REFERENCES inventory.stock_item (stock_item_id),
    CONSTRAINT fk_stocktake_line_location FOREIGN KEY (warehouse_location_id) REFERENCES inventory.warehouse_location (warehouse_location_id),
    CONSTRAINT fk_stocktake_line_lot_item FOREIGN KEY (stock_item_id, stock_lot_id) REFERENCES inventory.stock_lot (stock_item_id, stock_lot_id),
    CONSTRAINT ck_stocktake_line_number CHECK (line_number > 0),
    CONSTRAINT ck_stocktake_line_quantities CHECK (system_quantity >= 0 AND (counted_quantity IS NULL OR counted_quantity >= 0))
);

CREATE UNIQUE INDEX uq_stocktake_line_without_lot
    ON inventory.stocktake_line (stocktake_id, stock_item_id, warehouse_location_id)
    WHERE stock_lot_id IS NULL;

CREATE UNIQUE INDEX uq_stocktake_line_with_lot
    ON inventory.stocktake_line (stocktake_id, stock_item_id, warehouse_location_id, stock_lot_id)
    WHERE stock_lot_id IS NOT NULL;

CREATE TABLE inventory.stock_movement (
    stock_movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_document_type varchar(40) NOT NULL,
    source_document_id bigint NOT NULL,
    source_document_line_id bigint NOT NULL,
    movement_leg varchar(20) NOT NULL DEFAULT 'single',
    movement_type varchar(32) NOT NULL,
    stock_item_id bigint NOT NULL,
    warehouse_location_id bigint NOT NULL,
    stock_lot_id bigint NULL,
    quantity_delta numeric(18, 6) NOT NULL,
    posted_at timestamptz NOT NULL DEFAULT now(),
    posted_by_user_id bigint NULL,
    reversal_of_movement_id bigint NULL,
    idempotency_key varchar(120) NOT NULL,
    CONSTRAINT uq_stock_movement_source_leg UNIQUE (source_document_type, source_document_id, source_document_line_id, movement_leg),
    CONSTRAINT uq_stock_movement_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_stock_movement_item FOREIGN KEY (stock_item_id) REFERENCES inventory.stock_item (stock_item_id),
    CONSTRAINT fk_stock_movement_location FOREIGN KEY (warehouse_location_id) REFERENCES inventory.warehouse_location (warehouse_location_id),
    CONSTRAINT fk_stock_movement_lot_item FOREIGN KEY (stock_item_id, stock_lot_id) REFERENCES inventory.stock_lot (stock_item_id, stock_lot_id),
    CONSTRAINT fk_stock_movement_reversal FOREIGN KEY (reversal_of_movement_id) REFERENCES inventory.stock_movement (stock_movement_id),
    CONSTRAINT ck_stock_movement_quantity_nonzero CHECK (quantity_delta <> 0),
    CONSTRAINT ck_stock_movement_receipt_positive CHECK (movement_type <> 'receipt' OR quantity_delta > 0),
    CONSTRAINT ck_stock_movement_issue_negative CHECK (movement_type <> 'issue' OR quantity_delta < 0),
    CONSTRAINT ck_stock_movement_transfer_direction CHECK (movement_type <> 'transfer' OR ((movement_leg = 'source' AND quantity_delta < 0) OR (movement_leg = 'destination' AND quantity_delta > 0))),
    CONSTRAINT ck_stock_movement_leg CHECK (movement_leg IN ('single', 'source', 'destination', 'adjustment', 'reversal')),
    CONSTRAINT ck_stock_movement_type CHECK (movement_type IN ('receipt', 'issue', 'transfer', 'stocktake_adjustment', 'return', 'reversal'))
);

CREATE TABLE inventory.stock_balance (
    stock_balance_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_item_id bigint NOT NULL,
    warehouse_location_id bigint NOT NULL,
    stock_lot_id bigint NULL,
    on_hand_quantity numeric(18, 6) NOT NULL DEFAULT 0,
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT fk_stock_balance_item FOREIGN KEY (stock_item_id) REFERENCES inventory.stock_item (stock_item_id),
    CONSTRAINT fk_stock_balance_location FOREIGN KEY (warehouse_location_id) REFERENCES inventory.warehouse_location (warehouse_location_id),
    CONSTRAINT fk_stock_balance_lot_item FOREIGN KEY (stock_item_id, stock_lot_id) REFERENCES inventory.stock_lot (stock_item_id, stock_lot_id),
    CONSTRAINT ck_stock_balance_nonnegative CHECK (on_hand_quantity >= 0)
);

CREATE UNIQUE INDEX uq_stock_balance_without_lot
    ON inventory.stock_balance (stock_item_id, warehouse_location_id)
    WHERE stock_lot_id IS NULL;

CREATE UNIQUE INDEX uq_stock_balance_with_lot
    ON inventory.stock_balance (stock_item_id, warehouse_location_id, stock_lot_id)
    WHERE stock_lot_id IS NOT NULL;

CREATE INDEX ix_stock_item_type_status ON inventory.stock_item (item_type, status);
CREATE INDEX ix_stock_lot_expiry ON inventory.stock_lot (expires_on) WHERE expires_on IS NOT NULL;
CREATE INDEX ix_receipt_warehouse_status_date ON inventory.receipt (warehouse_id, status, created_at DESC);
CREATE INDEX ix_receipt_line_item ON inventory.receipt_line (stock_item_id, receipt_id);
