CREATE INDEX ix_transfer_status_date ON inventory.transfer (status, created_at DESC);
CREATE INDEX ix_stocktake_warehouse_status ON inventory.stocktake (warehouse_id, status);
CREATE INDEX ix_stocktake_line_item_location ON inventory.stocktake_line (stock_item_id, warehouse_location_id);
CREATE INDEX ix_stock_movement_item_location_time ON inventory.stock_movement (stock_item_id, warehouse_location_id, posted_at DESC);
CREATE INDEX ix_stock_movement_lot_time ON inventory.stock_movement (stock_lot_id, posted_at DESC) WHERE stock_lot_id IS NOT NULL;
CREATE INDEX ix_stock_movement_source ON inventory.stock_movement (source_document_type, source_document_id);
CREATE INDEX ix_stock_balance_item_location ON inventory.stock_balance (stock_item_id, warehouse_location_id);
