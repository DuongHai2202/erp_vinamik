CREATE TABLE inventory.transfer (
    transfer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_code varchar(60) NOT NULL,
    source_warehouse_id bigint NOT NULL,
    destination_warehouse_id bigint NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'draft',
    idempotency_key varchar(120) NULL,
    notes text NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    created_by_user_id bigint NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    updated_by_user_id bigint NULL,
    posted_at timestamptz NULL,
    posted_by_user_id bigint NULL,
    CONSTRAINT uq_transfer_code UNIQUE (transfer_code),
    CONSTRAINT uq_transfer_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT fk_transfer_source_warehouse FOREIGN KEY (source_warehouse_id) REFERENCES inventory.warehouse (warehouse_id),
    CONSTRAINT fk_transfer_destination_warehouse FOREIGN KEY (destination_warehouse_id) REFERENCES inventory.warehouse (warehouse_id),
    CONSTRAINT ck_transfer_status CHECK (status IN ('draft', 'pending', 'posted', 'cancelled'))
);

CREATE TABLE inventory.transfer_line (
    transfer_line_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id bigint NOT NULL,
    line_number integer NOT NULL,
    stock_item_id bigint NOT NULL,
    stock_lot_id bigint NULL,
    source_location_id bigint NOT NULL,
    destination_location_id bigint NOT NULL,
    quantity numeric(18, 6) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_transfer_line_number UNIQUE (transfer_id, line_number),
    CONSTRAINT fk_transfer_line_transfer FOREIGN KEY (transfer_id) REFERENCES inventory.transfer (transfer_id),
    CONSTRAINT fk_transfer_line_item FOREIGN KEY (stock_item_id) REFERENCES inventory.stock_item (stock_item_id),
    CONSTRAINT fk_transfer_line_source_location FOREIGN KEY (source_location_id) REFERENCES inventory.warehouse_location (warehouse_location_id),
    CONSTRAINT fk_transfer_line_destination_location FOREIGN KEY (destination_location_id) REFERENCES inventory.warehouse_location (warehouse_location_id),
    CONSTRAINT fk_transfer_line_lot_item FOREIGN KEY (stock_item_id, stock_lot_id) REFERENCES inventory.stock_lot (stock_item_id, stock_lot_id),
